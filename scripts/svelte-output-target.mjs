/**
 * Svelte output target.
 *
 * `@stencil/svelte-output-target` is still 0.0.3 and calls the Svelte 3/4
 * compiler API (`css: false`, `legacy`, `preserveComments`), which Svelte 5
 * rejects outright — so we generate the wrappers here instead.
 *
 * What comes out is plain Svelte 5 source, which is how Svelte libraries are
 * normally published: consumers' bundlers compile the `.svelte` files. That
 * means no build step and no preprocessor for this package — the `.svelte`
 * files stay JS-only and the types live in a generated `index.d.ts` built from
 * Stencil's own `Components` / `JSX` declarations.
 */

const pascalCase = (tag) =>
  tag
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

/** Stencil's JSX naming for an event handler: `valueChange` -> `onValueChange`. */
const handlerName = (eventName) => `on${eventName.charAt(0).toUpperCase()}${eventName.slice(1)}`;

/**
 * The bindable prop for a component, or null. Driven by `componentBindings`
 * rather than inferred, because a `valueChange` event does not always carry a
 * single value — `material-date-range-field` emits `{start, end}`.
 */
const bindingFor = (tagName, componentBindings) => {
  for (const binding of componentBindings) {
    const elements = Array.isArray(binding.elements) ? binding.elements : [binding.elements];
    if (elements.includes(tagName)) return binding;
  }
  return null;
};

const BANNER = `<!-- Generated by @viewflow/material. Do not edit. -->`;

const componentSource = (cmp, opts) => {
  const { componentCorePackage, customElementsDir } = opts;
  const binding = bindingFor(cmp.tagName, opts.componentBindings);
  const events = cmp.events.filter((event) => !event.internal);

  const props = ['element = $bindable(undefined)', 'children'];
  if (binding) props.push(`${binding.targetProp} = $bindable(undefined)`);
  for (const event of events) props.push(handlerName(event.name));
  props.push('...rest');

  const listeners = events.map((event) => {
    const forward = `${handlerName(event.name)}?.(event)`;
    const body =
      binding && event.name === binding.event
        ? `${binding.targetProp} = event.detail?.${binding.detailProp ?? binding.targetProp}; ${forward};`
        : `${forward};`;
    return `      ['${event.name}', (event) => { ${body} }],`;
  });

  // The bound prop is applied explicitly so it is not shadowed by `rest`.
  const boundAttr = binding ? ` {${binding.targetProp}}` : '';

  return `${BANNER}
<script>
  import { defineCustomElement } from '${componentCorePackage}/${customElementsDir}/${cmp.tagName}.js';

  defineCustomElement();

  let {
${props.map((prop) => `    ${prop}`).join(',\n')}
  } = $props();
${
  events.length
    ? `
  $effect(() => {
    const el = element;
    if (!el) return;
    const listeners = [
${listeners.join('\n')}
    ];
    for (const [name, handler] of listeners) el.addEventListener(name, handler);
    return () => {
      for (const [name, handler] of listeners) el.removeEventListener(name, handler);
    };
  });
`
    : ''
}</script>

<${cmp.tagName} bind:this={element}${boundAttr} {...rest}>{@render children?.()}</${cmp.tagName}>
`;
};

const indexSource = (components) =>
  [
    '/* Generated by @viewflow/material. Do not edit. */',
    ...components.map(
      (cmp) => `export { default as ${pascalCase(cmp.tagName)} } from './lib/${pascalCase(cmp.tagName)}.svelte';`,
    ),
    '',
  ].join('\n');

const typingsSource = (components, opts) => {
  const lines = [
    '/* Generated by @viewflow/material. Do not edit. */',
    "import type { Component, Snippet } from 'svelte';",
    `import type { JSX } from '${opts.componentCorePackage}';`,
    '',
    '/** Props every wrapper accepts on top of the component\'s own. */',
    'interface WrapperProps {',
    '  /** The underlying custom element. Use `bind:element` to reach its methods. */',
    '  element?: HTMLElement;',
    '  children?: Snippet;',
    '  class?: string;',
    '  style?: string;',
    '}',
    '',
  ];

  for (const cmp of components) {
    const name = pascalCase(cmp.tagName);
    const binding = bindingFor(cmp.tagName, opts.componentBindings);
    const bindings = ["'element'", ...(binding ? [`'${binding.targetProp}'`] : [])].join(' | ');
    lines.push(
      `export type ${name}Props = JSX.${name} & WrapperProps;`,
      `export declare const ${name}: Component<${name}Props, {}, ${bindings}>;`,
      '',
    );
  }

  return lines.join('\n');
};

/**
 * @param {object} outputTarget
 * @param {string} outputTarget.componentCorePackage npm name of the Stencil library
 * @param {string} outputTarget.outDir directory the Svelte package sources are written to
 * @param {string} outputTarget.customElementsDir path to the custom elements build inside the package
 * @param {string[]} [outputTarget.excludeComponents]
 * @param {{elements: string|string[], event: string, targetProp: string, detailProp?: string}[]} [outputTarget.componentBindings]
 */
export const svelteOutputTarget = (outputTarget) => ({
  type: 'custom',
  name: 'svelte-library',
  async generator(config, compilerCtx, buildCtx) {
    const timespan = buildCtx.createTimeSpan('generate svelte started', true);
    const path = await import('node:path');

    const opts = {
      componentBindings: [],
      excludeComponents: [],
      ...outputTarget,
    };

    const components = buildCtx.components
      .filter((cmp) => !cmp.internal && !opts.excludeComponents.includes(cmp.tagName))
      .sort((a, b) => (a.tagName < b.tagName ? -1 : 1));

    const outDir = path.isAbsolute(opts.outDir) ? opts.outDir : path.join(config.rootDir, opts.outDir);

    await Promise.all(
      components.map((cmp) =>
        compilerCtx.fs.writeFile(
          path.join(outDir, 'lib', `${pascalCase(cmp.tagName)}.svelte`),
          componentSource(cmp, opts),
        ),
      ),
    );
    await compilerCtx.fs.writeFile(path.join(outDir, 'index.js'), indexSource(components));
    await compilerCtx.fs.writeFile(path.join(outDir, 'index.d.ts'), typingsSource(components, opts));

    timespan.finish('generate svelte finished');
  },
});
