// The package's light-DOM stylesheet: some components (material-data-table,
// material-breadcrumbs, and whatever else follows the same server-first
// design later) enhance server-rendered markup that never enters a shadow
// root, so their CSS can't ship as a Stencil styleUrl — it has to live in
// the host document's own stylesheet. The demo build gets this by importing
// them into src/global/material.css under Tailwind's `components` layer;
// this script re-reads that same file for its `layer(components)` imports
// and concatenates the sources they point at, so css/material.css can never
// drift from what the demo site actually ships. Add a new light-DOM
// component by adding its import line to material.css — this script picks
// it up automatically.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { BUNDLE_BANNER, strip } from './license-header.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const globalDir = join(root, 'src/global');
const entry = readFileSync(join(globalDir, 'material.css'), 'utf8');

const importRe = /@import\s+"([^"]+)"\s+layer\(components\)\s*;/g;
const sources = [...entry.matchAll(importRe)].map((m) => m[1]);

if (sources.length === 0) {
  throw new Error('no `layer(components)` imports found in src/global/material.css');
}

const banner = `${BUNDLE_BANNER}

/* material.css — the library's light-DOM stylesheet.
 *
 * Generated by scripts/build-material-css.mjs from the same
 * \`layer(components)\` imports src/global/material.css uses for the demo
 * build, so this file can't drift from what the demo site ships. Components
 * that read server-rendered markup directly instead of a shadow root
 * (material-data-table, material-breadcrumbs, and any later addition with
 * the same server-first design) need their styling to live in the host
 * page's own stylesheet — load this alongside theme.css wherever one of
 * them appears:
 *
 *   <link rel="stylesheet" href="theme.css">
 *   <link rel="stylesheet" href="material.css">
 *
 * Do not edit this file — edit the component's own .css under src/components/.
 */
`;

// Each source carries the licence notice; the banner above states it once for
// the whole file, so the per-source copies come back out.
const body = sources
  .map((relPath) => {
    const path = join(globalDir, relPath);
    return strip(readFileSync(path, 'utf8'), path).trimEnd();
  })
  .join('\n\n');

writeFileSync(join(root, 'css/material.css'), `${banner}\n${body}\n`);

console.log(`css/material.css — bundled ${sources.length} light-DOM component stylesheet(s)`);
